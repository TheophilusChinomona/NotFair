-- Migrate campaign benchmarks from daily account/campaign/day facts to compact
-- trailing-30-day account/campaign snapshots.
--
-- Destructive step: after the 30d snapshot table is populated and verified in
-- the same transaction, the old daily campaign_benchmark_snapshots table is
-- truncated so it no longer stores daily benchmark rows.

CREATE TABLE IF NOT EXISTS campaign_benchmark_30d_snapshots (
  id serial PRIMARY KEY,
  account_id text NOT NULL,
  campaign_id text NOT NULL,
  snapshot_as_of_date date NOT NULL,
  window_start_date date NOT NULL,
  window_end_date date NOT NULL,
  window_days integer NOT NULL DEFAULT 30,
  observed_days integer NOT NULL DEFAULT 0,

  ad_network_type text NOT NULL DEFAULT 'ALL',
  device text NOT NULL DEFAULT 'ALL',

  campaign_name text,
  campaign_status text,
  advertising_channel_type text,
  bidding_strategy_type text,

  currency_code text NOT NULL DEFAULT 'UNKNOWN',
  time_zone text,
  industry_category text,
  business_niche text,
  business_domain text,
  business_landing_page_url text,

  geo_target_count integer NOT NULL DEFAULT 0,
  negative_geo_target_count integer NOT NULL DEFAULT 0,
  language_target_count integer NOT NULL DEFAULT 0,
  geo_target_constants jsonb NOT NULL DEFAULT '[]'::jsonb,
  language_constants jsonb NOT NULL DEFAULT '[]'::jsonb,

  impressions integer NOT NULL DEFAULT 0,
  clicks integer NOT NULL DEFAULT 0,
  cost_micros bigint NOT NULL DEFAULT 0,
  conversions double precision NOT NULL DEFAULT 0,
  conversions_value double precision NOT NULL DEFAULT 0,

  search_impression_share double precision,
  search_top_impression_share double precision,
  search_absolute_top_impression_share double precision,
  search_budget_lost_impression_share double precision,
  search_rank_lost_impression_share double precision,

  has_sitelinks boolean NOT NULL DEFAULT false,
  sitelink_count integer NOT NULL DEFAULT 0,
  has_callouts boolean NOT NULL DEFAULT false,
  callout_count integer NOT NULL DEFAULT 0,
  has_structured_snippets boolean NOT NULL DEFAULT false,
  structured_snippet_count integer NOT NULL DEFAULT 0,
  has_image_assets boolean NOT NULL DEFAULT false,
  image_asset_count integer NOT NULL DEFAULT 0,

  keyword_broad_impressions integer NOT NULL DEFAULT 0,
  keyword_broad_clicks integer NOT NULL DEFAULT 0,
  keyword_broad_cost_micros bigint NOT NULL DEFAULT 0,
  keyword_broad_conversions double precision NOT NULL DEFAULT 0,
  keyword_broad_conversions_value double precision NOT NULL DEFAULT 0,
  keyword_phrase_impressions integer NOT NULL DEFAULT 0,
  keyword_phrase_clicks integer NOT NULL DEFAULT 0,
  keyword_phrase_cost_micros bigint NOT NULL DEFAULT 0,
  keyword_phrase_conversions double precision NOT NULL DEFAULT 0,
  keyword_phrase_conversions_value double precision NOT NULL DEFAULT 0,
  keyword_exact_impressions integer NOT NULL DEFAULT 0,
  keyword_exact_clicks integer NOT NULL DEFAULT 0,
  keyword_exact_cost_micros bigint NOT NULL DEFAULT 0,
  keyword_exact_conversions double precision NOT NULL DEFAULT 0,
  keyword_exact_conversions_value double precision NOT NULL DEFAULT 0,

  created_at timestamp DEFAULT now() NOT NULL,
  updated_at timestamp DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS campaign_benchmark_30d_account_campaign_asof_idx
  ON campaign_benchmark_30d_snapshots (account_id, campaign_id, snapshot_as_of_date);

CREATE INDEX IF NOT EXISTS campaign_benchmark_30d_peer_slice_idx
  ON campaign_benchmark_30d_snapshots (
    industry_category,
    business_niche,
    currency_code,
    advertising_channel_type,
    snapshot_as_of_date
  );

CREATE INDEX IF NOT EXISTS campaign_benchmark_30d_channel_asof_idx
  ON campaign_benchmark_30d_snapshots (advertising_channel_type, snapshot_as_of_date);

ALTER TABLE campaign_benchmark_30d_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE campaign_benchmark_30d_snapshots FROM anon, authenticated;
REVOKE ALL ON SEQUENCE campaign_benchmark_30d_snapshots_id_seq FROM anon, authenticated;

WITH bounds AS (
  SELECT MAX(snapshot_date::date) AS as_of_date
  FROM campaign_benchmark_snapshots
), source_rows AS (
  SELECT d.*, b.as_of_date
  FROM campaign_benchmark_snapshots d
  CROSS JOIN bounds b
  WHERE b.as_of_date IS NOT NULL
    AND d.snapshot_date::date BETWEEN (b.as_of_date - 29) AND b.as_of_date
), rolled AS (
  SELECT
    account_id,
    campaign_id,
    as_of_date AS snapshot_as_of_date,
    (as_of_date - 29) AS window_start_date,
    as_of_date AS window_end_date,
    30 AS window_days,
    COUNT(DISTINCT snapshot_date)::int AS observed_days,

    COALESCE((array_agg(ad_network_type ORDER BY snapshot_date::date DESC, created_at DESC))[1], 'ALL') AS ad_network_type,
    COALESCE((array_agg(device ORDER BY snapshot_date::date DESC, created_at DESC))[1], 'ALL') AS device,
    (array_agg(campaign_name ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS campaign_name,
    (array_agg(campaign_status ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS campaign_status,
    (array_agg(advertising_channel_type ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS advertising_channel_type,
    (array_agg(bidding_strategy_type ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS bidding_strategy_type,
    COALESCE((array_agg(currency_code ORDER BY snapshot_date::date DESC, created_at DESC))[1], 'UNKNOWN') AS currency_code,
    (array_agg(time_zone ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS time_zone,
    (array_agg(industry_category ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS industry_category,
    (array_agg(business_niche ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS business_niche,
    (array_agg(business_domain ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS business_domain,
    (array_agg(business_landing_page_url ORDER BY snapshot_date::date DESC, created_at DESC))[1] AS business_landing_page_url,

    COALESCE((array_agg(geo_target_count ORDER BY snapshot_date::date DESC, created_at DESC))[1], 0) AS geo_target_count,
    COALESCE((array_agg(negative_geo_target_count ORDER BY snapshot_date::date DESC, created_at DESC))[1], 0) AS negative_geo_target_count,
    COALESCE((array_agg(language_target_count ORDER BY snapshot_date::date DESC, created_at DESC))[1], 0) AS language_target_count,
    COALESCE((array_agg(geo_target_constants ORDER BY snapshot_date::date DESC, created_at DESC))[1], '[]'::jsonb) AS geo_target_constants,
    COALESCE((array_agg(language_constants ORDER BY snapshot_date::date DESC, created_at DESC))[1], '[]'::jsonb) AS language_constants,

    COALESCE(SUM(impressions), 0)::int AS impressions,
    COALESCE(SUM(clicks), 0)::int AS clicks,
    COALESCE(SUM(cost_micros), 0)::bigint AS cost_micros,
    COALESCE(SUM(conversions), 0)::double precision AS conversions,
    COALESCE(SUM(conversions_value), 0)::double precision AS conversions_value,

    AVG(search_impression_share) FILTER (WHERE search_impression_share IS NOT NULL) AS search_impression_share,
    AVG(search_top_impression_share) FILTER (WHERE search_top_impression_share IS NOT NULL) AS search_top_impression_share,
    AVG(search_absolute_top_impression_share) FILTER (WHERE search_absolute_top_impression_share IS NOT NULL) AS search_absolute_top_impression_share,
    AVG(search_budget_lost_impression_share) FILTER (WHERE search_budget_lost_impression_share IS NOT NULL) AS search_budget_lost_impression_share,
    AVG(search_rank_lost_impression_share) FILTER (WHERE search_rank_lost_impression_share IS NOT NULL) AS search_rank_lost_impression_share,

    BOOL_OR(has_sitelinks) AS has_sitelinks,
    COALESCE(MAX(sitelink_count), 0) AS sitelink_count,
    BOOL_OR(has_callouts) AS has_callouts,
    COALESCE(MAX(callout_count), 0) AS callout_count,
    BOOL_OR(has_structured_snippets) AS has_structured_snippets,
    COALESCE(MAX(structured_snippet_count), 0) AS structured_snippet_count,
    BOOL_OR(has_image_assets) AS has_image_assets,
    COALESCE(MAX(image_asset_count), 0) AS image_asset_count,

    COALESCE(SUM(keyword_broad_impressions), 0)::int AS keyword_broad_impressions,
    COALESCE(SUM(keyword_broad_clicks), 0)::int AS keyword_broad_clicks,
    COALESCE(SUM(keyword_broad_cost_micros), 0)::bigint AS keyword_broad_cost_micros,
    COALESCE(SUM(keyword_broad_conversions), 0)::double precision AS keyword_broad_conversions,
    COALESCE(SUM(keyword_broad_conversions_value), 0)::double precision AS keyword_broad_conversions_value,
    COALESCE(SUM(keyword_phrase_impressions), 0)::int AS keyword_phrase_impressions,
    COALESCE(SUM(keyword_phrase_clicks), 0)::int AS keyword_phrase_clicks,
    COALESCE(SUM(keyword_phrase_cost_micros), 0)::bigint AS keyword_phrase_cost_micros,
    COALESCE(SUM(keyword_phrase_conversions), 0)::double precision AS keyword_phrase_conversions,
    COALESCE(SUM(keyword_phrase_conversions_value), 0)::double precision AS keyword_phrase_conversions_value,
    COALESCE(SUM(keyword_exact_impressions), 0)::int AS keyword_exact_impressions,
    COALESCE(SUM(keyword_exact_clicks), 0)::int AS keyword_exact_clicks,
    COALESCE(SUM(keyword_exact_cost_micros), 0)::bigint AS keyword_exact_cost_micros,
    COALESCE(SUM(keyword_exact_conversions), 0)::double precision AS keyword_exact_conversions,
    COALESCE(SUM(keyword_exact_conversions_value), 0)::double precision AS keyword_exact_conversions_value
  FROM source_rows
  GROUP BY account_id, campaign_id, as_of_date
)
